kode_aplikasi = """import streamlit as st
import google.generativeai as genai

st.set_page_config(page_title="PyTutor AI", page_icon="🐍", layout="centered")
st.title("🐍 PyTutor AI - Asisten Belajar Python")
st.write("Tanyakan apa saja seputar pemrograman Python!")

api_key = st.sidebar.text_input("Masukkan Gemini API Key:", type="password")
gaya_bahasa = st.sidebar.selectbox("Gaya Bahasa Tutor:", ["Santai & Ramah", "Formal & Akademis"])

# Menempatkan gemini-3.8-flash sebagai model utama
daftar_model = [
    "gemini-3.8-flash",
    "gemini-2.5-flash",
    "gemini-2.0-flash"
]
pilihan_model = st.sidebar.selectbox("Model AI Aktif:", daftar_model)

if api_key:
    genai.configure(api_key=api_key)
    instruksi = f"Kamu adalah PyTutor AI, asisten belajar Python. Gunakan gaya bahasa yang {gaya_bahasa}."

    if "messages" not in st.session_state:
        st.session_state.messages = []

    for msg in st.session_state.messages:
        with st.chat_message(msg["role"]):
            st.markdown(msg["content"])

    prompt = st.chat_input("Ketik pertanyaan Python Anda di sini...")
    if prompt:
        st.session_state.messages.append({"role": "user", "content": prompt})
        with st.chat_message("user"):
            st.markdown(prompt)

        with st.chat_message("assistant"):
            with st.spinner("PyTutor sedang mengetik jawaban..."):
                kandidat_model = [pilihan_model] + [m for m in daftar_model if m != pilihan_model]
                berhasil = False

                riwayat_gemini = [
                    {"role": "user" if m["role"] == "user" else "model", "parts": [m["content"]]}
                    for m in st.session_state.messages[:-1]
                ]

                for nama_model in kandidat_model:
                    try:
                        model = genai.GenerativeModel(nama_model, system_instruction=instruksi)
                        chat = model.start_chat(history=riwayat_gemini)
                        response = chat.send_message(prompt)

                        st.markdown(response.text)
                        if nama_model != pilihan_model:
                            st.caption(f"*(Catatan: Kuota harian {pilihan_model} penuh, dijawab menggunakan {nama_model})*")
                        st.session_state.messages.append({"role": "assistant", "content": response.text})
                        berhasil = True
                        break
                    except Exception:
                        continue

                if not berhasil:
                    st.error("Semua kuota model pada API Key ini sedang penuh.")
else:
    st.info("👈 Masukkan Gemini API Key Anda di menu sebelah kiri untuk memulai.")
"""

with open("app.py", "w") as file:
    file.write(kode_aplikasi)

print("✅ File app.py berhasil diperbarui dengan dukungan utama gemini-3.8-flash!")

